ALTER TABLE offer_snapshot
    ADD COLUMN basis_price NUMERIC;

CREATE TABLE offer_payment_condition (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_snapshot_id BIGINT NOT NULL,
    condition_type TEXT NOT NULL,
    price NUMERIC,
    discount_percentage NUMERIC,
    installment_count INTEGER,
    installment_amount NUMERIC,
    installment_total NUMERIC,
    interest NUMERIC,

    CONSTRAINT fk_offer_payment_condition_offer_snapshot
        FOREIGN KEY (offer_snapshot_id)
        REFERENCES offer_snapshot (id)
);

CREATE TABLE offer_payment_condition_method (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_condition_id BIGINT NOT NULL,
    payment_method TEXT NOT NULL,

    CONSTRAINT fk_payment_condition_method_condition
        FOREIGN KEY (payment_condition_id)
        REFERENCES offer_payment_condition (id)
);

CREATE INDEX idx_offer_payment_condition_snapshot
    ON offer_payment_condition (offer_snapshot_id);

CREATE INDEX idx_offer_payment_condition_method_condition
    ON offer_payment_condition_method (payment_condition_id);