/*
 * FASE 8.5-C3
 *
 * Persiste os resultados individuais das regras que participaram
 * de uma DealEvaluation.
 *
 * deal_evaluation continua representando a decisão agregada.
 * deal_evaluation_rule_result representa a explicação detalhada.
 */

CREATE TABLE deal_evaluation_rule_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    /*
     * Avaliação agregada à qual a regra pertence.
     */
    deal_evaluation_id BIGINT NOT NULL,

    /*
     * Posição determinística da regra dentro da avaliação.
     *
     * A ordem é relevante porque o primeiro resultado que falha
     * também define o rejection_reason principal da avaliação atual.
     */
    rule_order INTEGER NOT NULL,

    /*
     * Código estável da regra.
     *
     * Exemplos:
     *
     * SELLER_IS_AMAZON
     * DELIVERY_IS_AMAZON
     */
    rule_code TEXT NOT NULL,

    /*
     * Resultado individual da regra.
     */
    passed BOOLEAN NOT NULL,

    /*
     * Valor observado pela regra.
     *
     * Exemplos:
     *
     * AMAZON
     * THIRD_PARTY
     * UNKNOWN
     */
    observed_value TEXT NOT NULL,

    /*
     * Valor exigido pela regra.
     *
     * Na política atual:
     *
     * AMAZON
     */
    threshold_value TEXT NOT NULL,

    /*
     * Código controlado que explica a falha.
     *
     * Deve ser NULL quando a regra passou.
     */
    reason_code TEXT,

    CONSTRAINT fk_deal_evaluation_rule_result_evaluation
        FOREIGN KEY (deal_evaluation_id)
        REFERENCES deal_evaluation (id)
        ON DELETE CASCADE,

    /*
     * Uma avaliação não pode ter duas regras ocupando
     * a mesma posição.
     */
    CONSTRAINT uq_deal_evaluation_rule_order
        UNIQUE (deal_evaluation_id, rule_order),

    /*
     * Nesta arquitetura cada código de regra aparece uma única
     * vez dentro da mesma avaliação.
     */
    CONSTRAINT uq_deal_evaluation_rule_code
        UNIQUE (deal_evaluation_id, rule_code)
);

CREATE INDEX idx_deal_evaluation_rule_result_evaluation
    ON deal_evaluation_rule_result (deal_evaluation_id);

CREATE INDEX idx_deal_evaluation_rule_result_code
    ON deal_evaluation_rule_result (rule_code);