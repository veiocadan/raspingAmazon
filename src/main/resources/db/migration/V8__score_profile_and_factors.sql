/*
 * FASE 10-E
 *
 * Introduz:
 *
 * 1. configuração persistida e versionada do score;
 * 2. persistência dos fatores individuais que explicam
 *    o score de uma DealEvaluation.
 *
 * deal_evaluation continua armazenando:
 *
 * - score agregado;
 * - score_version.
 *
 * deal_evaluation_score_factor armazena a decomposição auditável
 * que permite reproduzir e explicar esse score.
 */


/* ================================================================
 * SCORE PROFILE
 * ================================================================ */

CREATE TABLE score_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    /*
     * Identidade semântica e estável da configuração.
     *
     * Esta versão é armazenada em:
     *
     * deal_evaluation.score_version
     */
    version TEXT NOT NULL,

    /*
     * Pesos dos fatores ativos.
     *
     * Os valores representam pontos máximos de contribuição.
     * Cada peso deve permanecer entre 0 e 100.
     */
    sold_percentage_weight NUMERIC(7, 4) NOT NULL,
    cash_discount_weight NUMERIC(7, 4) NOT NULL,
    rating_weight NUMERIC(7, 4) NOT NULL,
    review_count_weight NUMERIC(7, 4) NOT NULL,

    /*
     * Quantidade de avaliações a partir da qual REVIEW_COUNT
     * atinge normalização igual a 100.
     */
    review_count_full_score_threshold BIGINT NOT NULL,

    /*
     * Somente um ScoreProfile pode estar ativo por vez.
     */
    active BOOLEAN NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_score_profile_version
        UNIQUE (version),

    CONSTRAINT ck_score_profile_sold_percentage_weight_range
        CHECK (
            sold_percentage_weight >= 0
            AND sold_percentage_weight <= 100
        ),

    CONSTRAINT ck_score_profile_cash_discount_weight_range
        CHECK (
            cash_discount_weight >= 0
            AND cash_discount_weight <= 100
        ),

    CONSTRAINT ck_score_profile_rating_weight_range
        CHECK (
            rating_weight >= 0
            AND rating_weight <= 100
        ),

    CONSTRAINT ck_score_profile_review_count_weight_range
        CHECK (
            review_count_weight >= 0
            AND review_count_weight <= 100
        ),

    /*
     * O domínio permite versões futuras cuja soma de pesos seja
     * inferior ou igual a 100.
     *
     * SCORE_V1 soma 90 porque os 10 pontos originalmente reservados
     * à atratividade de preço não são redistribuídos.
     */
    CONSTRAINT ck_score_profile_total_weight
        CHECK (
            sold_percentage_weight
            + cash_discount_weight
            + rating_weight
            + review_count_weight
            <= 100
        ),

    CONSTRAINT ck_score_profile_review_count_threshold_positive
        CHECK (
            review_count_full_score_threshold > 0
        )
);

/*
 * PostgreSQL permite índice único parcial.
 *
 * Isso garante estruturalmente no máximo um perfil ativo,
 * preservando qualquer quantidade de versões históricas inativas.
 */
CREATE UNIQUE INDEX uq_score_profile_single_active
    ON score_profile (active)
    WHERE active = true;


/* ================================================================
 * SCORE_V1
 * ================================================================ */

/*
 * Primeira configuração operacional da FASE 10.
 *
 * Pesos definidos pela ADR-0002:
 *
 * SOLD_PERCENTAGE = 30
 * CASH_DISCOUNT   = 25
 * RATING          = 20
 * REVIEW_COUNT    = 15
 *
 * Soma ativa = 90.
 *
 * review_count_full_score_threshold = 1000
 *
 * Essa linha representa configuração histórica imutável.
 * Mudanças futuras devem criar SCORE_V2, SCORE_V3 etc.
 */
INSERT INTO score_profile (
    version,
    sold_percentage_weight,
    cash_discount_weight,
    rating_weight,
    review_count_weight,
    review_count_full_score_threshold,
    active
)
VALUES (
